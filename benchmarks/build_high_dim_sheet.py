"""
build_high_dim_sheet.py
=======================

Rebuild the ``High-dim Ref`` sheet of ``benchmark_results.xlsx`` from the
committed certified reference JSON files.

Every other artifact in this folder is generated by a script; this sheet was
not, so it drifted from the data (it kept a dimension-256 primary time of
2,744 s from a standalone run long after the same-node sweep measured 86.6 s
for the identical calculation). This script closes that gap: it reads whatever
``data/high_dim_reference_spin_chain_dim*.json`` files exist, rewrites the
sheet from them, and leaves every other sheet in the workbook untouched.

Wall-clock caveat, stated on the sheet itself: times are comparable only within
a single sweep on a single node. The same certified dimension-256 reference
took 2,744 s standalone and 86.6 s inside a sequential same-node sweep, so a
column of times assembled from different jobs is not a scaling result.

Run:  python build_high_dim_sheet.py [--dims 4 8 ...] [--run-note "..."]
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from common import DATA_DIR

try:
    import openpyxl
    from openpyxl.styles import Alignment, Font
except ImportError as exc:  # pragma: no cover - environment guard
    raise SystemExit(
        "build_high_dim_sheet.py needs openpyxl (pip install openpyxl)"
    ) from exc


SHEET_NAME = "High-dim Ref"
WORKBOOK = Path(__file__).with_name("benchmark_results.xlsx")
FILE_PATTERN = "high_dim_reference_spin_chain_dim*.json"

SUMMARY_HEADERS = [
    "dimension", "sites", "Davies sectors", "Davies build (s)",
    "primary RK4 (s)", "check RK4 (s)", "total solver (s)",
    "max |dE|", "max trace distance", "tolerance", "status",
    "host", "Slurm job", "NPZ archive", "NPZ SHA-256",
]


def discover_dims() -> list[int]:
    dims = []
    for path in DATA_DIR.glob(FILE_PATTERN):
        match = re.search(r"dim(\d+)\.json$", path.name)
        if match:
            dims.append(int(match.group(1)))
    return sorted(dims)


def load_reference(dim: int) -> dict:
    path = DATA_DIR / f"high_dim_reference_spin_chain_dim{dim}.json"
    document = json.loads(path.read_text(encoding="utf-8"))
    point = document["point"]
    if point["dim"] != dim:
        raise ValueError(f"{path.name} records dimension {point['dim']}")
    if not point["selfcheck"].get("passed", False):
        raise ValueError(f"{path.name} is not a certified reference")
    return document


def execution_labels(meta: dict) -> tuple[str, str]:
    """(host, slurm job) as recorded, or a marker when the run predates it."""
    execution = meta.get("execution")
    if not execution:
        return "not recorded", "not recorded"
    slurm = execution.get("slurm", {})
    job = slurm.get("job_id", "-")
    nodes = slurm.get("nodelist")
    host = nodes or execution.get("hostname", "?")
    return str(host), str(job)


def write_sheet(worksheet, documents: list[dict], run_note: str) -> None:
    bold = Font(bold=True)
    title = Font(bold=True, size=13)

    worksheet["A1"] = "Certified high-dimensional spin-chain references"
    worksheet["A1"].font = title
    worksheet["A2"] = (
        "Native RK4 trajectories beyond the practical mesolve wall, each "
        "certified against a halved-substep run of the same calculation."
    )
    worksheet["A3"] = "Certification tolerance"
    worksheet["A3"].font = bold
    worksheet["B3"] = min(d["point"]["selfcheck"]["tol"] for d in documents)
    worksheet["A4"] = run_note
    worksheet["A4"].alignment = Alignment(wrap_text=False)

    header_row = 6
    for column, name in enumerate(SUMMARY_HEADERS, start=1):
        cell = worksheet.cell(row=header_row, column=column, value=name)
        cell.font = bold

    for offset, document in enumerate(documents):
        row = header_row + 1 + offset
        point, meta = document["point"], document["meta"]
        selfcheck = point["selfcheck"]
        archive = point.get("state_archive", {})
        host, job = execution_labels(meta)
        values = [
            point["dim"], point["n_sites"], point["n_l"],
            point["t_davies"], point["t_reference"],
            selfcheck.get("t_partner"),
            f"=E{row}+F{row}",
            selfcheck["max_abs_dev"], selfcheck["max_trace_distance"],
            selfcheck["tol"],
            f'=IF(AND(H{row}<=J{row},I{row}<=J{row}),"PASS","FAIL")',
            host, job,
            archive.get("filename", "-"), archive.get("sha256", "-"),
        ]
        for column, value in enumerate(values, start=1):
            worksheet.cell(row=row, column=column, value=value)

    # ---- dynamics block -------------------------------------------------
    first = documents[0]
    grid = first["meta"]["tlist"]
    n_times = grid["n"]
    step = (grid["t1"] - grid["t0"]) / (n_times - 1) if n_times > 1 else 0.0
    times = [grid["t0"] + step * i for i in range(n_times)]

    note_row = header_row + len(documents) + 2
    worksheet.cell(
        row=note_row, column=1,
        value=(f"Time grid: {grid['t0']:g} to {grid['t1']:g}, "
               f"{n_times} stored samples. Energy per site is total energy "
               f"divided by the site count in column B."),
    )

    dyn_header = note_row + 2
    headers = ["time"]
    headers += [f"total energy d{d['point']['dim']}" for d in documents]
    headers += [f"energy/site d{d['point']['dim']}" for d in documents]
    headers += [f"trace distance d{d['point']['dim']}" for d in documents]
    headers += ["tolerance"]
    for column, name in enumerate(headers, start=1):
        cell = worksheet.cell(row=dyn_header, column=column, value=name)
        cell.font = bold

    n_docs = len(documents)
    for index, time_value in enumerate(times):
        row = dyn_header + 1 + index
        worksheet.cell(row=row, column=1, value=time_value)
        for offset, document in enumerate(documents):
            energy = document["point"]["reference_energy"]
            worksheet.cell(row=row, column=2 + offset,
                           value=energy[index] if index < len(energy) else None)
            # Divide by that dimension's site count in the summary table above,
            # so the per-site column stays a live formula rather than a
            # duplicated number that can silently disagree with column B.
            energy_col = worksheet.cell(row=row, column=2 + offset).column_letter
            worksheet.cell(
                row=row, column=2 + n_docs + offset,
                value=f"={energy_col}{row}/$B${header_row + 1 + offset}",
            )
            trace = document["point"]["selfcheck"]["trace_distance_by_time"]
            worksheet.cell(row=row, column=2 + 2 * n_docs + offset,
                           value=trace[index] if index < len(trace) else None)
        worksheet.cell(row=row, column=2 + 3 * n_docs,
                       value=worksheet["B3"].value)

    worksheet.column_dimensions["A"].width = 22
    for column in "BCDEFGHIJKLMNO":
        worksheet.column_dimensions[column].width = 18


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument(
        "--dims", nargs="+", type=int, default=None,
        help="dimensions to include (default: every certified JSON found)",
    )
    parser.add_argument(
        "--workbook", type=Path, default=WORKBOOK,
        help="workbook to update in place",
    )
    parser.add_argument(
        "--run-note", default=(
            "Wall times are comparable only within one sweep on one node. "
            "Times assembled from separate jobs are NOT a scaling result: the "
            "same certified d=256 reference took 2,744 s standalone and 86.6 s "
            "inside a sequential same-node sweep."
        ),
        help="provenance line written above the summary table",
    )
    args = parser.parse_args()

    dims = args.dims if args.dims else discover_dims()
    if not dims:
        raise SystemExit(f"no {FILE_PATTERN} files found in {DATA_DIR}")
    documents = [load_reference(dim) for dim in dims]

    if not args.workbook.exists():
        raise SystemExit(f"workbook not found: {args.workbook}")
    workbook = openpyxl.load_workbook(args.workbook)
    if SHEET_NAME in workbook.sheetnames:
        position = workbook.sheetnames.index(SHEET_NAME)
        del workbook[SHEET_NAME]
    else:
        position = len(workbook.sheetnames)
    worksheet = workbook.create_sheet(SHEET_NAME, position)

    write_sheet(worksheet, documents, args.run_note)
    workbook.save(args.workbook)

    covered = ", ".join(str(d) for d in dims)
    print(f"rewrote '{SHEET_NAME}' in {args.workbook}")
    print(f"dimensions: {covered}")
    print(f"other sheets preserved: {len(workbook.sheetnames) - 1}")


if __name__ == "__main__":
    main()
